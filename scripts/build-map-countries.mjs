const round = (value) => Math.round(value * PRECISION) / PRECISION;

const roundRing = (ring) => {
  const points = [];
  for (const [lon, lat] of ring) {
    const point = [round(lon), round(lat)];
    const last = points.at(-1);
    if (!last || last[0] !== point[0] || last[1] !== point[1]) {
      points.push(point);
    }
  }
  return points;
};

const polygonsOf = (geometry) =>
  geometry.type === "Polygon" ? [geometry.coordinates] : geometry.coordinates;

const source = JSON.parse(readFileSync(SOURCE, "utf8"));
const countries = source.features
  .filter((feature) => !DROPPED.has(feature.id))
  .map((feature) => ({
    id: feature.id,
    name: NAMES_PT[feature.properties.name] ?? feature.properties.name,
    polygons: polygonsOf(feature.geometry).map((polygon) =>
      polygon.map(roundRing).filter((ring) => ring.length >= 4)
    ),
  }));

writeFileSync(OUTPUT, `${JSON.stringify(countries)}\n`);
console.log(`${countries.length} countries in ${OUTPUT}`);
